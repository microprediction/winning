"""A rise in the classic inverse's miss is not a plateau (#923).

The #904 stall rule stopped once two successive iterates failed to beat
the best miss. A 31-cell atomic market generated by the exact forward
rises for two steps at iterations 21-22 and then converges: it stopped at
2.17e-4, silently, where the iteration reaches 9.4e-9. A stall is now an
iterate whose miss equals the best (to a relative 1e-6), the #842
plateau, so a rise resets the count, in python, the browser and R.
"""
import json
import shutil
import subprocess
import warnings

import numpy as np
import pytest

from winning.classic.lattice import skew_normal_density, state_prices_from_offsets
from winning.classic.lattice_calibration import solve_for_implied_offsets, dividend_implied_ability

ATOMS = np.zeros(31)
ATOMS[[2, 18, 23, 26, 28, 30]] = [0.10, 0.05, 0.30, 0.05, 0.45, 0.05]
TRUTH = [5.5, 1.0, -7.0, 6.0]
TARGET = [float(x) for x in state_prices_from_offsets(ATOMS, TRUTH)]
NODE = shutil.which("node")


def _miss(density, target, mu):
    return float(np.max(np.abs(np.asarray(state_prices_from_offsets(density, mu)) - np.asarray(target))))


@pytest.fixture
def numpy_path(monkeypatch):
    # the numpy spec path, which CI runs; a locally built fastrace may predate later kernel fixes
    import winning.classic.lattice_calibration as lc
    monkeypatch.setattr(lc, "_HAVE_RUST", False)


def test_a_two_step_rise_does_not_stop_the_atomic_inverse(numpy_path):
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        mu = solve_for_implied_offsets(TARGET, ATOMS, nIter=100)
        ab = dividend_implied_ability([1 / p for p in TARGET], ATOMS)
    assert _miss(ATOMS, TARGET, mu) <= 1e-6                     # was 2.17e-4
    assert _miss(ATOMS, TARGET, ab) <= 1e-6


def test_the_rise_is_still_there_and_the_best_iterate_is_returned(numpy_path):
    # iterations 21-22 miss by more than iteration 20: a budget ending
    # inside the rise returns iteration 20, the best assessed
    at20 = solve_for_implied_offsets(TARGET, ATOMS, nIter=20)
    for n in (21, 22):
        np.testing.assert_array_equal(solve_for_implied_offsets(TARGET, ATOMS, nIter=n), at20)
    assert _miss(ATOMS, TARGET, solve_for_implied_offsets(TARGET, ATOMS, nIter=23)) < _miss(ATOMS, TARGET, at20)


def test_ordinary_books_are_unchanged_by_the_rule(numpy_path):
    # smooth densities converge monotonically to tol: same answers, same steps
    d = skew_normal_density(100, 0.05, a=1.0)
    rng = np.random.default_rng(923)
    for n in (2, 4, 9, 16):
        p = rng.dirichlet(np.ones(n))
        mu = solve_for_implied_offsets(p, d)
        assert _miss(d, p, mu) <= 1e-9


@pytest.mark.skipif(NODE is None, reason="node is not installed")
def test_browser_port_runs_through_the_rise():
    script = f"""
import {{ solveForImpliedOffsets, dividendImpliedAbility, statePricesFromOffsets }} from "./docs/js/winning/classic.mjs";
const density = {json.dumps(list(map(float, ATOMS)))};
const target = {json.dumps(TARGET)};
console.warn = () => {{ throw new Error("warned"); }};
const mu = solveForImpliedOffsets(target, density, {{ nIter: 100 }});
const ab = dividendImpliedAbility(target.map(p => 1 / p), density);
console.log(JSON.stringify({{ mu, ab }}));
"""
    out = subprocess.run([NODE, "--input-type=module", "-e", script], capture_output=True, text=True, check=True)
    got = json.loads(out.stdout.strip().splitlines()[-1])
    assert _miss(ATOMS, TARGET, got["mu"]) <= 1e-6                # was 2.17e-4
    assert _miss(ATOMS, TARGET, got["ab"]) <= 1e-6
