"""Bounded deterministic retry of the top-k inverses (#779, #781).

A single damped trajectory can stall at a non-solution: the exact-rank
inverse from a near-truth warm start (#779), and the normal loc/scale
inverse from its cold start (#781). Only then is the solve retried from
a fixed few starts; a first-try success is untouched."""
import json
import os
import shutil
import subprocess
import warnings
from pathlib import Path

import numpy as np
import pytest

from winning.factor import topk as T

# #779: a logistic four-runner exact-second target and a warm start within
# 0.048 of the generating field
MU_779 = [0.016, -0.356, 0.552, -0.212]
D_779 = [x * x for x in (1.444, 0.799, 0.818, 1.163)]
MU0_779 = [-0.002, -0.308, 0.574, -0.242]

# #781: an exact normal win/top-2 board
MU_781 = [-0.6669408707331521, -0.04607137189844819, -0.9239086741190706,
          1.2201504898506477, -0.7018494832934388, 1.1186199101934622]
SD_781 = [2.601365880665001, 1.5539670145121982, 1.122141854005653,
          0.4148305666148936, 0.43663998310753704, 0.3415875902805172]


@pytest.mark.parametrize("points", [257, 513, 1025])
def test_779_exact_rank_inverse_rescued(points):
    """Generated by the public map, so the target is attainable: the
    inverse must reprice it exactly, and the rescue lands on the
    generating branch rather than some other one."""
    t = T.rank_probabilities(MU_779, D=D_779, base="logistic",
                             points=points)[:, 1]
    mu, info = T.abilities_from_rank_marginal(
        t, 2, mu0=MU0_779, D=D_779, base="logistic", points=points,
        n_iter=200, return_info=True)
    assert info["converged"], info
    assert info["max_logit_residual"] < 1e-8
    back = T.rank_probabilities(mu, D=D_779, base="logistic",
                                points=points)[:, 1]
    assert np.abs(back - t).max() < 1e-8
    truth = np.asarray(MU_779) - np.mean(MU_779)
    assert np.abs(mu - truth).max() < 1e-6


def _board(points=513):
    D = np.asarray(SD_781) ** 2
    q1 = T.top_k_probabilities(MU_781, 1, D=D, points=points)
    q2 = T.top_k_probabilities(MU_781, 2, D=D, points=points)
    return q1, q2


def _reprice(mu, sd, q1, q2, points=513):
    r1 = T.top_k_probabilities(mu, 1, D=sd ** 2, points=points)
    r2 = T.top_k_probabilities(mu, 2, D=sd ** 2, points=points)
    return max(np.abs(r1 - q1).max(), np.abs(r2 - q2).max())


@pytest.mark.parametrize("points", [513, 1025])
def test_781_loc_scale_cold_start_rescued(points):
    """The default cold start used to stop at logit residual 0.219, a
    five-point repricing miss; both entry points now round-trip."""
    q1, q2 = _board(points)
    mu, sd, info = T.loc_scale_from_topk_pair(q1, 1, q2, 2, points=points,
                                              n_iter=300, return_info=True)
    assert info["converged"] and info["fit_converged"], info
    assert _reprice(mu, sd, q1, q2, points) < 1e-8
    mu, sd, info = T.loc_scale_from_win_and_second(
        q1, q2 - q1, points=points, n_iter=300, return_info=True)
    assert info["converged"], info
    assert _reprice(mu, sd, q1, q2, points) < 1e-8


def test_781_rescue_agrees_with_the_generating_scales():
    """The rescued solution is the D0=D one (up to the gauge)."""
    q1, q2 = _board()
    mu, sd, _ = T.loc_scale_from_topk_pair(q1, 1, q2, 2, return_info=True)
    mw, sw, _ = T.loc_scale_from_topk_pair(q1, 1, q2, 2,
                                           D0=np.asarray(SD_781) ** 2,
                                           return_info=True)
    assert np.abs(sd - sw).max() < 1e-6
    assert np.abs(mu - mw).max() < 1e-6


def _forbid_retry(monkeypatch):
    def boom(*a, **k):
        raise AssertionError("retry fired on an input that converges")
    monkeypatch.setattr(T, "_rank_marginal_starts", boom)
    monkeypatch.setattr(T, "_loc_scale_starts", boom)


def test_ordinary_inputs_never_retry(monkeypatch):
    """The retry is gated on failure: ordinary inverses near both fixes
    converge first time and never build a retry start."""
    _forbid_retry(monkeypatch)
    rng = np.random.default_rng(779781)
    for n in (4, 6, 9):
        mu = rng.normal(0, 0.5, n)
        D = np.exp(rng.normal(0, 0.3, n)) ** 2
        for base in ("normal", "logistic"):
            q1 = T.top_k_probabilities(mu, 1, D=D, base=base)
            q2 = T.top_k_probabilities(mu, 2, D=D, base=base)
            _, _, info = T.loc_scale_from_topk_pair(q1, 1, q2, 2, base=base,
                                                    return_info=True)
            assert info["converged"]
            t = T.rank_probabilities(mu, D=D, base=base)[:, 1]
            _, info = T.abilities_from_rank_marginal(
                t, 2, mu0=mu + 0.03, D=D, base=base, return_info=True)
            assert info["converged"]


def test_near_fixture_inputs_unchanged(monkeypatch):
    """Next to each fixture, the inputs that converged before still do,
    from the first start: the issue's nudged warm start (#779) and the
    D0=D solve (#781)."""
    _forbid_retry(monkeypatch)
    t = T.rank_probabilities(MU_779, D=D_779, base="logistic")[:, 1]
    mu0 = list(MU0_779)
    mu0[1] -= 0.01
    _, info = T.abilities_from_rank_marginal(t, 2, mu0=mu0, D=D_779,
                                             base="logistic",
                                             return_info=True)
    assert info["converged"]
    q1, q2 = _board()
    _, _, info = T.loc_scale_from_topk_pair(
        q1, 1, q2, 2, D0=np.asarray(SD_781) ** 2, return_info=True)
    assert info["converged"] and info["iterations"] == 2


def test_supplied_starts_are_not_retried(monkeypatch):
    """#781's retry replaces the internal cold start only: a caller's
    D0 or mu0 is never overridden."""
    _forbid_retry(monkeypatch)
    q1 = [0.8, 0.1, 0.1]
    q2 = [0.2, 0.9, 0.9]          # infeasible: no (mu, sigma) fits it
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        _, _, info = T.loc_scale_from_topk_pair(q1, 1, q2, 2, D0=[1, 1, 1],
                                                return_info=True)
    assert not info["converged"]


def test_every_start_failing_is_reported_honestly():
    """An infeasible board fails from every start: the best attempt
    comes back converged=False, its iterations the total spent, and the
    non-convergence warning still fires without return_info."""
    q1 = [0.8, 0.1, 0.1]
    q2 = [0.2, 0.9, 0.9]
    calls = []
    real = T._loc_scale_once

    def counting(*a, **k):
        out = real(*a, **k)
        calls.append(out[-1]["iterations"])
        return out

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        T._loc_scale_once = counting
        try:
            _, _, info = T.loc_scale_from_topk_pair(q1, 1, q2, 2,
                                                    return_info=True)
        finally:
            T._loc_scale_once = real
    assert len(calls) == 2
    assert not info["converged"]
    assert info["iterations"] == sum(calls)
    with pytest.warns(RuntimeWarning, match="did not converge"):
        T.loc_scale_from_topk_pair(q1, 1, q2, 2)


# ------------------------------------------------------------ browser port

NODE = shutil.which("node")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _node(script):
    out = subprocess.run([NODE, "--input-type=module", "-e", script],
                         capture_output=True, text=True, check=True,
                         timeout=300)
    return json.loads(out.stdout)


@pytest.mark.skipif(NODE is None, reason="node is not installed")
def test_browser_retry_rescues_both_fixtures_and_matches_python():
    mod = json.dumps(Path(ROOT, "docs", "js", "winning",
                          "topk.mjs").as_uri())
    got = _node(f"""
import {{ rankProbabilities, abilitiesFromRankMarginal, topKProbabilities,
         locScaleFromTopkPair, locScaleFromWinAndSecond }} from {mod};
const D7 = {json.dumps(D_779)};
const t = rankProbabilities({json.dumps(MU_779)},
  {{ D: D7, base: "logistic" }}).map(r => r[1]);
const a = abilitiesFromRankMarginal(t, 2, {{ mu0: {json.dumps(MU0_779)},
  D: D7, base: "logistic", nIter: 200, returnInfo: true }});
const sd = {json.dumps(SD_781)}, D = sd.map(x => x * x);
const mu = {json.dumps(MU_781)};
const q1 = topKProbabilities(mu, 1, {{ D }}), q2 = topKProbabilities(mu, 2, {{ D }});
const b = locScaleFromTopkPair(q1, 1, q2, 2, {{ returnInfo: true }});
const c = locScaleFromWinAndSecond(q1, q2.map((x, i) => x - q1[i]),
  {{ returnInfo: true }});
console.log(JSON.stringify({{ a, b, c }}));
""")
    for key in ("a", "b", "c"):
        assert got[key]["info"]["converged"], (key, got[key]["info"])
    t = T.rank_probabilities(MU_779, D=D_779, base="logistic")[:, 1]
    mu, _ = T.abilities_from_rank_marginal(t, 2, mu0=MU0_779, D=D_779,
                                           base="logistic", n_iter=200,
                                           return_info=True)
    assert np.abs(np.asarray(got["a"]["mu"]) - mu).max() < 1e-8
    q1, q2 = _board()
    mu, sd, _ = T.loc_scale_from_topk_pair(q1, 1, q2, 2, return_info=True)
    assert np.abs(np.asarray(got["b"]["mu"]) - mu).max() < 1e-8
    assert np.abs(np.asarray(got["b"]["sd"]) - sd).max() < 1e-8


def test_zero_iteration_budget_is_not_retried(monkeypatch):
    """n_iter=0 prices the start and performs no update (#441, #497): a
    failing zero-budget call returns its own start, never a retry's."""
    _forbid_retry(monkeypatch)
    t = T.rank_probabilities(MU_779, D=D_779, base="logistic")[:, 1]
    mu, info = T.abilities_from_rank_marginal(t, 2, mu0=MU0_779, D=D_779,
                                              base="logistic", n_iter=0,
                                              return_info=True)
    assert info["iterations"] == 0 and not info["converged"]
    assert np.array_equal(mu, np.asarray(MU0_779) - np.mean(MU0_779))
    q1, q2 = _board()
    _, _, info = T.loc_scale_from_topk_pair(q1, 1, q2, 2, n_iter=0,
                                            return_info=True)
    assert info["iterations"] == 0
