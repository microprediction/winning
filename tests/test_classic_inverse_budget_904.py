"""The classic inverse iterates to a tolerance, not a fixed three sweeps (#904).

A three-runner two-atom market generated by the exact forward from the
offsets [-1, 0, 1] came back 1.27 points off after the default three
defect-correction sweeps, with a warning but no way to ask the dividend
wrapper for more. The default is now a budget of CALIBRATION_MAX_ITER
steps with early stopping once the exact reprice is within
CALIBRATION_TOL of every target, in python, the browser and R alike.
"""
import json
import shutil
import subprocess
import warnings

import numpy as np
import pytest

from winning.classic.lattice import skew_normal_density, state_prices_from_offsets
from winning.classic.lattice_calibration import (CALIBRATION_MAX_ITER, CALIBRATION_TOL,
                                                 dividend_implied_ability, solve_for_implied_offsets,
                                                 state_price_implied_ability)

DENSITY = [0, 0, 0.2, 0, 0.8, 0, 0]          # L=3, two atoms
TRUTH = [-1, 0, 1]
TARGET = state_prices_from_offsets(DENSITY, TRUTH)
NODE = shutil.which("node")


def _miss(density, target, mu):
    return float(np.max(np.abs(np.asarray(state_prices_from_offsets(density, mu)) - np.asarray(target))))


def test_defaults_are_documented_values():
    assert CALIBRATION_MAX_ITER == 100
    assert CALIBRATION_TOL == 1e-6


def test_atomic_market_round_trips_at_defaults_without_warning():
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        mu = solve_for_implied_offsets(TARGET, DENSITY)
    assert _miss(DENSITY, TARGET, mu) <= CALIBRATION_TOL          # was 0.0127
    np.testing.assert_allclose(mu, TRUTH, atol=1e-4)


def test_dividend_wrapper_converges_and_takes_the_budget():
    dividends = [1 / p for p in TARGET]
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        mu = dividend_implied_ability(dividends, DENSITY)
        mu2 = state_price_implied_ability(TARGET, DENSITY)
    assert _miss(DENSITY, TARGET, mu) <= CALIBRATION_TOL
    np.testing.assert_allclose(mu, mu2)
    # the budget is honoured when asked for: three sweeps is the old answer
    with pytest.warns(RuntimeWarning, match="did not reach the target"):
        short = dividend_implied_ability(dividends, DENSITY, nIter=3)
    assert abs(_miss(DENSITY, TARGET, short) - 0.012728827747) < 1e-9
    # a loose tolerance stops early
    loose = dividend_implied_ability(dividends, DENSITY, tol=1e-2)
    assert 1e-6 < _miss(DENSITY, TARGET, loose) <= 1e-2


def test_early_stop_leaves_ordinary_books_converged():
    d = skew_normal_density(500, 0.01, a=1.5)
    rng = np.random.default_rng(1)
    for n in (2, 5, 8, 14):
        p = rng.dirichlet(np.ones(n) * 0.7)
        with warnings.catch_warnings():
            warnings.simplefilter("error")
            mu = solve_for_implied_offsets(p, d)
        assert _miss(d, p, mu) <= CALIBRATION_TOL
        # with the tolerance met, more budget changes nothing
        np.testing.assert_array_equal(mu, solve_for_implied_offsets(p, d, nIter=10 * CALIBRATION_MAX_ITER))


PLATEAU_DENSITY = [0] * 9 + [0.0625, 0.125, 0.1875, 0.25, 0.1875, 0.125, 0.0625] + [0] * 9
PLATEAU_TRUTH = [-0.3870526359606288, -3.8859224668266945, -0.5618939753478802,
                 -6.990429141603045, 0.6690584211927497]            # the #842 fixture


def test_a_plateau_stops_after_two_stalled_steps_and_returns_the_best_iterate(monkeypatch):
    # the straggler is priced at exactly zero where its target is 1.86e-6:
    # the miss cannot fall below the target, the table has no gradient
    # there, and the offset drifted for the whole budget. The numpy spec
    # path, which CI runs: a fastrace built before the #842 interpolation
    # fix walks a different path on this fixture.
    import winning.classic.lattice_calibration as lc
    monkeypatch.setattr(lc, "_HAVE_RUST", False)
    target = state_prices_from_offsets(PLATEAU_DENSITY, PLATEAU_TRUTH)
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        mu = solve_for_implied_offsets(target, PLATEAU_DENSITY)
    assert _miss(PLATEAU_DENSITY, target, mu) < 2e-6
    # iterates four and later all miss by the same 1.86e-6, so the fourth
    # is returned whatever the budget beyond it
    np.testing.assert_array_equal(mu, solve_for_implied_offsets(target, PLATEAU_DENSITY, nIter=4))
    np.testing.assert_array_equal(mu, solve_for_implied_offsets(target, PLATEAU_DENSITY, nIter=7))


@pytest.mark.parametrize("tol", [0, -1e-6, float("nan"), float("inf"), None, "1e-6"])
def test_bad_tolerance_is_refused(tol):
    d = skew_normal_density(50, 0.1)
    with pytest.raises((ValueError, TypeError), match="tol"):
        solve_for_implied_offsets([0.6, 0.3, 0.1], d, tol=tol)


@pytest.mark.skipif(NODE is None, reason="node is not installed")
def test_browser_port_agrees_on_the_atomic_market():
    script = f"""
import {{ solveForImpliedOffsets, dividendImpliedAbility, statePricesFromOffsets,
         CALIBRATION_MAX_ITER, CALIBRATION_TOL }} from "./docs/js/winning/classic.mjs";
const density = {json.dumps(DENSITY)};
const target = {json.dumps(list(map(float, TARGET)))};
console.warn = () => {{ throw new Error("warned at defaults"); }};
const mu = solveForImpliedOffsets(target, density);
const div = dividendImpliedAbility(target.map(p => 1 / p), density);
console.warn = () => {{}};
const short = dividendImpliedAbility(target.map(p => 1 / p), density, {{ nIter: 3 }});
console.log(JSON.stringify({{ mu, div, short, back: statePricesFromOffsets(density, mu),
  consts: [CALIBRATION_MAX_ITER, CALIBRATION_TOL] }}));
"""
    out = subprocess.run([NODE, "--input-type=module", "-e", script], capture_output=True, text=True, check=True)
    got = json.loads(out.stdout.strip().splitlines()[-1])
    assert got["consts"] == [CALIBRATION_MAX_ITER, CALIBRATION_TOL]
    mu = solve_for_implied_offsets(TARGET, DENSITY)
    np.testing.assert_allclose(got["mu"], mu, atol=1e-9)
    np.testing.assert_allclose(got["div"], mu, atol=1e-9)
    assert float(np.max(np.abs(np.asarray(got["back"]) - np.asarray(TARGET)))) <= CALIBRATION_TOL
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        np.testing.assert_allclose(got["short"], solve_for_implied_offsets(TARGET, DENSITY, nIter=3), atol=1e-9)
