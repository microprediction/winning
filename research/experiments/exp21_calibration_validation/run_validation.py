"""Experiment 21: calibration validation suite (fifth/sixth review rounds).

  A. Noiseless inverse test (deliberate inverse crime): targets generated by
     the same lattice map, inverted; max utility error over ALL
     alternatives, iterations, residual. Separates solver error from
     target-sampling error.
  B. Noisy-target decomposition at N=1000: the MC-target inversion with part
     A's solver error alongside: recovery error decomposes into solver error
     (tiny) plus target sampling noise (dominant).
  C. Robustness: 20 problems varying utility spread, factor strength,
     D-heterogeneity, and rank; iterations, wall time, convergence,
     recovery on shares above 1e-3.
  D. Self-convergence certificates at N=1000 and N=5000: forward map at
     (L=1501, GH15) versus (L=3001, GH21).

Run:  python experiments/exp21_calibration_validation/run_validation.py
Output: results.csv
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "exp13_ghk_benchmark"))
from raceutil import (  # noqa: E402
    abilities_from_probabilities_factor,
    hermite_nodes,
    win_probabilities_factor,
)
from run_ghk_benchmark import make_problem, mc_shares  # noqa: E402

HERE = Path(__file__).resolve().parent
SEED = 21


def main():
    rng = np.random.default_rng(SEED)
    rows = ["part,quantity,value"]

    print("Part A: noiseless inverse test (inverse crime, solver plumbing)")
    for n in (200, 1000):
        mu, V, D = make_problem(n, 2, rng, spread=1.5)
        mu -= mu.mean()
        F, W = hermite_nodes(2)
        target = win_probabilities_factor(mu, V, D, F, W)
        t0 = time.perf_counter()
        mu_hat, info = abilities_from_probabilities_factor(
            target, V, D, F, W, return_info=True)
        dt = time.perf_counter() - t0
        # align means WITHIN each tier: the solver's mean-zero projection is
        # over all N coordinates, and unresolvable tail coordinates would
        # otherwise leak a common shift into the well-resolved errors
        tiers = {"all": np.ones(n, bool),
                 "share>1e-7": target > 1e-7,
                 "share>3e-4": target > 3e-4}
        err = {}
        for k_, v in tiers.items():
            d_ = (mu_hat[v] - mu_hat[v].mean()) - (mu[v] - mu[v].mean())
            err[k_] = np.abs(d_).max()
        msg = ", ".join(f"{k_}: {err[k_]:.1e}" for k_ in tiers)
        print(f"  N={n}: max utility error by tier [{msg}], "
              f"{info['iterations']} iterations, residual {info['residual']:.1e}, "
              f"{dt:.0f}s")
        for k_ in tiers:
            rows.append(f"A,N{n}_max_err_{k_},{err[k_]:.3e}")
        rows += [f"A,N{n}_iterations,{info['iterations']}",
                 f"A,N{n}_residual,{info['residual']:.3e}"]

    print("\nPart B: noisy-target decomposition, N=1000")
    n = 1000
    mu, V, D = make_problem(n, 2, rng, spread=1.5)
    mu -= mu.mean()
    F, W = hermite_nodes(2)
    target = mc_shares(mu, V, D, 5_000_000, seed=41)
    target = np.maximum(target, 1e-9); target /= target.sum()
    a_hat, info = abilities_from_probabilities_factor(
        target, V, D, F, W, return_info=True)
    util_hat = -a_hat                     # argmax targets: min-wins a = -mu
    res = target > 3e-4
    rec = np.abs((util_hat - util_hat[res].mean())
                 - (mu - mu[res].mean()))[res].max()
    print(f"  recovery vs truth (well-resolved set): {rec:.3f}; noiseless "
          f"solver error (part A) is orders smaller, so this is target "
          f"sampling noise, not solver error")
    rows += [f"B,recovery_max,{rec:.4f}", f"B,iterations,{info['iterations']}"]

    print("\nPart C: robustness over 20 problems (N=500)")
    print(f"{'spread':>7} {'vscale':>7} {'Drange':>12} {'k':>2} "
          f"{'iters':>5} {'sec':>5} {'conv':>5} {'rec>1e-3':>9}")
    fails = 0
    prng = np.random.default_rng(5)
    for t in range(20):
        spread = float(prng.choice([1.0, 1.5, 2.0]))
        vscale = float(prng.choice([0.3, 0.7]))
        dlo, dhi = [(0.5, 1.5), (0.1, 1.0)][int(prng.integers(2))]
        k = int(prng.choice([1, 2, 3]))
        n = 500
        mu = prng.normal(0, spread, n); mu -= mu.mean()
        V = prng.normal(0, vscale / np.sqrt(k), (n, k))
        D = prng.uniform(dlo, dhi, n)
        Fk, Wk = hermite_nodes(k)
        target = mc_shares(mu, V, D, 2_000_000, seed=100 + t)
        target = np.maximum(target, 1e-9); target /= target.sum()
        t0 = time.perf_counter()
        a_hat, info = abilities_from_probabilities_factor(
            target, V, D, Fk, Wk, return_info=True)
        dt = time.perf_counter() - t0
        util_hat = -a_hat                 # argmax targets: min-wins a = -mu
        res = target > 1e-3
        rec = np.abs((util_hat - util_hat[res].mean())
                     - (mu - mu[res].mean()))[res].max()
        fails += not info["converged"]
        print(f"{spread:>7} {vscale:>7} {f'[{dlo},{dhi}]':>12} {k:>2} "
              f"{info['iterations']:>5} {dt:>5.0f} {str(info['converged']):>5} "
              f"{rec:>9.3f}")
        rows.append(f"C,{t},spread={spread};v={vscale};D=[{dlo},{dhi}];k={k};"
                    f"iters={info['iterations']};sec={dt:.1f};"
                    f"conv={info['converged']};rec={rec:.4f}")
    print(f"  convergence failures: {fails}/20")
    rows.append(f"C,failures,{fails}")

    print("\nPart D: self-convergence certificates at large N")
    for n in (1000, 5000):
        mu, V, D = make_problem(n, 2, rng, spread=1.5)
        F1, W1 = hermite_nodes(2, Q=15)
        F2, W2 = hermite_nodes(2, Q=21)
        pa = win_probabilities_factor(mu, V, D, F1, W1, points=1501)
        pb = win_probabilities_factor(mu, V, D, F2, W2, points=3001)
        d = np.abs(pa - pb).max()
        print(f"  N={n}: (L=1501, GH15) vs (L=3001, GH21): {d:.1e}")
        rows.append(f"D,N{n}_selfconv,{d:.3e}")

    (HERE / "results.csv").write_text("\n".join(rows) + "\n")
    print("wrote results.csv")


if __name__ == "__main__":
    main()
