"""Experiment 35: inversion validated against a methodologically
independent high-accuracy forward map.

The gap this closes: independent simulation references are too noisy
(~2e-4) to see the claimed numerical precision, while high-resolution
lattice references share the numerical method. Here target shares are
generated by the per-alternative factor-conditioned RQMC integral of
experiment 24 (a (k+1)-dimensional scrambled-Sobol evaluation, sharing
no code path with the lattice), at 2^17 points. The lattice calibration
then inverts those targets and must recover the known utilities.

Run:  python experiments/exp35_independent_inversion/run_independent.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "exp13_ghk_benchmark"))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "exp24_factor_rqmc"))
from raceutil import abilities_from_probabilities_factor, hermite_nodes  # noqa: E402
from run_ghk_benchmark import make_problem  # noqa: E402
from run_factor_rqmc import factor_rqmc_shares  # noqa: E402

HERE = Path(__file__).resolve().parent
SEED = 35


def main():
    rng = np.random.default_rng(SEED)
    F, W = hermite_nodes(2)
    lines = []
    for n in (50, 100, 200):
        mu, V, D = make_problem(n, 2, rng, spread=1.0)
        mu -= mu.mean()
        target = factor_rqmc_shares(mu, V, D, 17)          # max-wins shares
        check = factor_rqmc_shares(mu, V, D, 16, seed=12)  # target self-check
        tgt_err = np.abs(target - check).max()
        a_hat = abilities_from_probabilities_factor(target, V, D, F, W)
        a_hat -= a_hat.mean()
        # utilities are identified up to location; tail coordinates carry
        # the target's absolute-error floor, so recenter on the
        # well-resolved set before scoring it
        err = a_hat - (-mu)
        parts = [f"N={n}: target self-check |dp|={tgt_err:.2e};"]
        for lo, tag in ((1e-2, "p>1e-2"), (1e-3, "p>1e-3")):
            m = target > lo
            e = err[m] - err[m].mean()
            parts.append(f" {tag} (recentered): max={np.abs(e).max():.2e} "
                         f"med={np.median(np.abs(e)):.2e} ({m.sum()});")
        m = target > 1e-4 / n
        parts.append(f" resolvable (raw): max={np.abs(err[m]).max():.2e};")
        lines.append("".join(parts))
        print(lines[-1])
    (HERE / "results.txt").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
